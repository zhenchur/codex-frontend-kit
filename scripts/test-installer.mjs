import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'codex-frontend-kit-test-'));
const testHome = path.join(scratch, 'home');
function run(...args) {
  const r = spawnSync(process.execPath, [path.join(root, 'scripts', 'install.mjs'), '--home', testHome, ...args], { encoding: 'utf8' });
  assert.equal(r.status, 0, r.stderr || r.stdout);
  return r.stdout;
}
run();
assert.ok(!fs.existsSync(testHome), 'dry-run writes nothing');
run('--apply');
const codex = path.join(testHome, '.codex');
const skills = path.join(testHome, '.agents', 'skills');
assert.equal(fs.readdirSync(skills).length, 9);
assert.ok(fs.existsSync(path.join(skills, 'frontend-react-workflow', 'SKILL.md')));
assert.ok(!fs.existsSync(path.join(codex, 'config.toml')), 'base config never created');
assert.ok(fs.existsSync(path.join(codex, 'frontend.config.toml')));
assert.ok(run('--apply').includes('"create":0'), 'repeat install is idempotent');
fs.writeFileSync(path.join(codex, 'AGENTS.md'), 'Keep my existing rules.\n');
fs.writeFileSync(path.join(codex, 'config.toml'), 'model = "existing-model"\n');
run('--apply');
assert.equal(fs.readFileSync(path.join(codex, 'AGENTS.md'), 'utf8'), 'Keep my existing rules.\n');
run('--apply', '--merge-agents', '--include-optional', '--include-command-rules');
const merged = fs.readFileSync(path.join(codex, 'AGENTS.md'), 'utf8');
assert.ok(merged.startsWith('Keep my existing rules.'));
assert.equal((merged.match(/codex-frontend-kit:start/g) || []).length, 1);
assert.equal(fs.readdirSync(skills).length, 11);
assert.ok(fs.existsSync(path.join(codex, 'rules', 'frontend-kit.rules')));
run('--apply', '--merge-agents');
assert.equal(fs.readFileSync(path.join(codex, 'AGENTS.md'), 'utf8'), merged, 'merge is idempotent');
const skillFile = path.join(skills, 'gsap-core', 'SKILL.md');
fs.writeFileSync(skillFile, 'Local edits');
fs.writeFileSync(path.join(codex, 'frontend.config.toml'), 'model = "local-profile"\n');
run('--apply');
assert.equal(fs.readFileSync(skillFile, 'utf8'), 'Local edits');
assert.equal(fs.readFileSync(path.join(codex, 'frontend.config.toml'), 'utf8'), 'model = "local-profile"\n');
run('--apply', '--replace-existing');
assert.ok(fs.readFileSync(skillFile, 'utf8').startsWith('---'));
assert.equal(fs.readFileSync(path.join(codex, 'config.toml'), 'utf8'), 'model = "existing-model"\n');
const backups = fs.readdirSync(path.join(codex, 'frontend-kit-backups'), { recursive: true });
assert.ok(backups.some(p => String(p).endsWith('AGENTS.md')));
assert.ok(backups.some(p => String(p).endsWith('SKILL.md')));
assert.ok(backups.some(p => String(p).endsWith('frontend.config.toml')));
console.log('Passed: dry-run, fresh install, idempotence, conflict preservation, merge, optional skills/rules, backups, untouched base config.');
console.log(`Test fixtures retained for inspection: ${scratch}`);
